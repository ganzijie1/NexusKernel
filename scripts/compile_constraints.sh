#!/usr/bin/env bash
set -euo pipefail

usage() {
    cat <<'EOF'
Usage: scripts/compile_constraints.sh [--check]

Compile the Python 3.11-3.13 universal constraints from pyproject.toml.
Use --check to fail when the committed constraints are stale.
EOF
}

fail() {
    printf 'Error: %s\n' "$1" >&2
    exit 1
}

check=false
case "${1:-}" in
    "")
        ;;
    --check)
        check=true
        ;;
    --help|-h)
        usage
        exit 0
        ;;
    *)
        fail "unknown option: $1"
        ;;
esac
(($# <= 1)) || fail "too many arguments"

[[ "$(uname -s)" == "Linux" ]] || fail "constraint compilation is Linux-only"

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
project_root="$(cd -- "$script_dir/.." && pwd -P)"
target="$project_root/constraints/py311-313.txt"
export UV_CACHE_DIR="${UV_CACHE_DIR:-${TMPDIR:-/tmp}/nexus-kernel-uv-cache}"
mkdir -p -- "$UV_CACHE_DIR"

uv_command=""
if [[ -x "$project_root/.venv-linux/bin/uv" ]]; then
    uv_command="$project_root/.venv-linux/bin/uv"
elif command -v uv >/dev/null 2>&1; then
    uv_command="$(command -v uv)"
fi
[[ -n "$uv_command" ]] || fail "uv==0.11.29 is required; run scripts/setup_python_env.sh"
case "$($uv_command --version)" in
    "uv 0.11.29"|"uv 0.11.29 "*)
        ;;
    *)
        fail "uv==0.11.29 is required"
        ;;
esac

mkdir -p -- "$(dirname -- "$target")"
body="$(mktemp)"
candidate="$(mktemp)"
trap 'rm -f -- "$body" "$candidate"' EXIT

compile_arguments=(
    pip compile
    pyproject.toml
    --all-extras
    --universal
    --python-version 3.11
    --no-annotate
    --no-header
    --quiet
    --output-file "$body"
)
[[ "$check" == false || -f "$target" ]] \
    || fail "missing generated constraints: $target"
if [[ "$check" == true ]]; then
    cp -- "$target" "$body"
else
    compile_arguments+=(--upgrade)
fi

cd -- "$project_root"
"$uv_command" "${compile_arguments[@]}"
{
    printf '%s\n' '# Generated by scripts/compile_constraints.sh; do not edit manually.'
    printf '%s\n' '# Source of truth: pyproject.toml'
    cat -- "$body"
} >"$candidate"

if [[ "$check" == true ]]; then
    cmp -s -- "$candidate" "$target" \
        || fail "constraints are stale; run scripts/compile_constraints.sh"
else
    mv -- "$candidate" "$target"
fi
